#!/usr/bin/env python3
"""Generate assumptions_ledger.md from src/estimates.py (single source of
truth) plus fixed modeling assumptions. Keeps report and code in lockstep."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from estimates import ESTIMATES

WS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

rows = []
for key, e in ESTIMATES.items():
    val = e["value"]
    if isinstance(val, dict):
        val = "; ".join(f"{k}={v}" for k, v in val.items())
    elif isinstance(val, list):
        val = f"{len(val)} entries: {val}"
    elif isinstance(val, float):
        val = f"{val:.6g}"
    rows.append((key, str(val), e["units"], e["status"], e["sensitivity"],
                 e["source"], e["rationale"]))

MODELING = [
    ("mass_lumping", "translational-only lumped mass (no beam rotary inertia); "
     "CONM2 rotary inertia kept", "-", "MODELING (D8)",
     "LOW <500 Hz (member torsion modes far above band)",
     "Nastran CBAR/CBEAM lumped default", "exact massless condensation"),
    ("beam_theory", "Timoshenko, deck shear factors K1=0.297/K2=0.624",
     "-", "MODELING (D9)", "validated: shear = 26% of stocky-case deflection",
     "deck PBEAM", "elements are 0.45-1.25 in stocky tube segments"),
    ("shell_formulation", "Q4 membrane + 12-DOF ACM Kirchhoff bending + "
     "relative drilling penalty (K6ROT-style)", "-", "MODELING (D10/D16)",
     "LOW (drill x100 arm: max 0.32% shift; Kirchhoff fine: shield thin, "
     "thrust plate quasi-rigid in band)", "deck PARAM K6ROT=100",
     "validated vs plate strip + SS plate closed forms"),
    ("cbush_offsets", "spring at GA-GB midpoint with rigid arms (S=0.5), "
     "basic frame", "-", "MODELING (D11)", "LOW (k=1e7 near-rigid)",
     "Nastran CBUSH default", "self-equilibrium validated"),
    ("feet_bc", "nominal SPC 123456 at grids 1/164/692/1212; variant: 1e8 "
     "grounding springs (base-flexibility knob)", "-", "MODELING (D12)",
     "MEDIUM (calibratable later)", "deck SPC1", "variant f1 shift < 0.01%"),
    ("damping", "NONE in this task (no FRF/response prediction; modes only)",
     "-", "MODELING", "n/a", "-", "future calibration prior, not needed for "
     "eigenfrequencies/shapes"),
    ("data_count", "ZERO test datasets used (pre-test prior model); test "
     "matrix exists but data not ingested this task", "-", "SCOPE", "n/a",
     "card", "no flight/test variability modeled -- nothing to model yet"),
    ("pid38_unused", "PBEAM 38 (A=3.9 flat bar) defined but unused by any "
     "element; dropped from groups", "-", "PARSE FACT (D25)", "none",
     "deck parse", "beam groups split wall-vs-rest instead"),
]

hdr = ("| key | value | units | status | sensitivity priority | source | "
       "rationale |")
sep = "|" + "---|" * 7
lines = [
    "# Assumptions Ledger — MPL Stand Parametric FEM Rebuild (FABLE, "
    "2026-06-11)", "",
    "Generated by `src/make_ledger.py` from `src/estimates.py` (single source "
    "of truth shared with the assembly code). Mass conversions: 1 lbm = "
    "1/386.089 lbf·s²/in. Units: inch-lbf-second throughout.", "",
    "**Every ESTIMATED row is ANDREW-CONFIRM-REQUIRED and is exposed as a "
    "model parameter (prior, not fact).**", "",
    "## Estimated / confirmed values", "", hdr, sep]
for r in rows:
    lines.append("| " + " | ".join(str(x).replace("|", "/") for x in r) + " |")
lines += ["", "## Modeling assumptions", "", hdr, sep]
for r in MODELING:
    lines.append("| " + " | ".join(str(x).replace("|", "/") for x in r) + " |")
lines += [
    "", "## Uncertainty-type ledger (Assumptions & Uncertainty Gate)", "",
    "- **Parameter uncertainty**: group scalars s_g (beam wall/rest, shield "
    "mem/bend, screw k, joint k, mount k, masses) — these are the future "
    "calibration targets; priors TBD in the sampler task.",
    "- **Observation noise / model discrepancy / forcing**: NOT modeled here "
    "(no data, no sampler this task); the robust-twin demo plans HIGH assumed "
    "model discrepancy by design.",
    "- **Boundary-condition uncertainty**: feet SPC vs grounding-spring "
    "variant (built, reported); shield screw stiffness (top knob).",
    "- **Aleatory / build-to-build / test-to-test**: absent — single physical "
    "stand, zero datasets ingested.",
    "- **QOI uncertainty**: QOI items (valve panel, electronics box, white "
    "box) carry ESTIMATED masses/locations/attachments → their local-mode "
    "frequencies are order-of-magnitude placements, not predictions.",
]
with open(os.path.join(WS, "assumptions_ledger.md"), "w") as fh:
    fh.write("\n".join(lines) + "\n")
print("wrote assumptions_ledger.md,", len(rows), "estimate rows,",
      len(MODELING), "modeling rows")
