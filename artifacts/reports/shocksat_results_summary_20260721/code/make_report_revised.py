def rgb(hex_value: str) -> RGBColor:
    return RGBColor.from_string(hex_value)


def set_repeat_table_header(row) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    element = OxmlElement("w:tblHeader")
    element.set(qn("w:val"), "true")
    tr_pr.append(element)


def keep_table_row_together(row) -> None:
    """Prevent Word/LibreOffice from splitting one logical row across pages."""
    tr_pr = row._tr.get_or_add_trPr()
    if tr_pr.find(qn("w:cantSplit")) is None:
        tr_pr.append(OxmlElement("w:cantSplit"))


def shade_cell(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def set_cell_width(cell, width_dxa: int) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_w = tc_pr.find(qn("w:tcW"))
    if tc_w is None:
        tc_w = OxmlElement("w:tcW")
        tc_pr.append(tc_w)
    tc_w.set(qn("w:w"), str(width_dxa))
    tc_w.set(qn("w:type"), "dxa")


def set_cell_margins(cell, top=80, start=110, bottom=80, end=110) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for name, value in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        node = tc_mar.find(qn(f"w:{name}"))
        if node is None:
            node = OxmlElement(f"w:{name}")
            tc_mar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def set_table_geometry(table, widths: list[int]) -> None:
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    tbl_pr = table._tbl.tblPr
    tbl_w = tbl_pr.find(qn("w:tblW"))
    if tbl_w is None:
        tbl_w = OxmlElement("w:tblW")
        tbl_pr.append(tbl_w)
    tbl_w.set(qn("w:w"), str(sum(widths)))
    tbl_w.set(qn("w:type"), "dxa")
    grid = table._tbl.tblGrid
    for child in list(grid):
        grid.remove(child)
    for width in widths:
        col = OxmlElement("w:gridCol")
        col.set(qn("w:w"), str(width))
        grid.append(col)
    for row in table.rows:
        for cell, width in zip(row.cells, widths):
            set_cell_width(cell, width)
            set_cell_margins(cell)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def set_cell_text(cell, text: str, bold=False, color=INK, size=8.7) -> None:
    cell.text = ""
    paragraph = cell.paragraphs[0]
    paragraph.paragraph_format.space_after = Pt(0)
    paragraph.paragraph_format.line_spacing = 1.0
    run = paragraph.add_run(text)
    run.bold = bold
    run.font.name = "Arial"
    run.font.size = Pt(size)
    run.font.color.rgb = rgb(color)


def add_table(doc: Document, headers: list[str], rows: list[list[str]], widths: list[int],
              status_column: int | None = None, font_size=8.7):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    for cell, header in zip(table.rows[0].cells, headers):
        shade_cell(cell, NAVY)
        set_cell_text(cell, header, bold=True, color=WHITE, size=font_size)
    set_repeat_table_header(table.rows[0])
    keep_table_row_together(table.rows[0])
    for values in rows:
        row = table.add_row()
        keep_table_row_together(row)
        for index, (cell, value) in enumerate(zip(row.cells, values)):
            fill = WHITE
            if status_column is not None and index == status_column:
                if value.startswith("GREEN"):
                    fill = PALE_GREEN
                elif value.startswith("YELLOW"):
                    fill = PALE_YELLOW
                elif value.startswith("RED"):
                    fill = "FCE8E6"
            shade_cell(cell, fill)
            set_cell_text(cell, value, size=font_size)
    set_table_geometry(table, widths)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return table


def set_alt_text(shape, description: str) -> None:
    inline = shape._inline
    doc_pr = inline.docPr
    doc_pr.set("descr", description)
    doc_pr.set("title", description.split(".")[0][:80])


def add_figure(doc: Document, filename: str, alt: str, caption: str, width=6.45) -> None:
    paragraph = doc.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.keep_with_next = True
    paragraph.paragraph_format.space_after = Pt(2)
    shape = paragraph.add_run().add_picture(str(FIGURES / filename), width=Inches(width))
    set_alt_text(shape, alt)
    cap = doc.add_paragraph(style="Caption")
    cap.paragraph_format.keep_together = True
    cap.paragraph_format.space_after = Pt(7)
    run = cap.add_run(caption)
    run.font.name = "Arial"
    run.font.size = Pt(8.2)
    run.font.bold = False
    run.font.italic = False
    run.font.color.rgb = rgb(GREY)


def add_paragraph(doc: Document, text: str = "", bold_lead: str | None = None,
                  italic=False, size: float | None = None, color=INK,
                  style: str | None = None, space_after=5):
    p = doc.add_paragraph(style=style)
    p.paragraph_format.space_after = Pt(space_after)
    if bold_lead and text.startswith(bold_lead):
        first = p.add_run(bold_lead)
        first.bold = True
        rest = p.add_run(text[len(bold_lead):])
        runs = [first, rest]
    else:
        runs = [p.add_run(text)]
    for run in runs:
        run.italic = italic
        run.font.name = "Arial"
        if size is not None:
            run.font.size = Pt(size)
        run.font.color.rgb = rgb(color)
    return p


def add_bullet(doc: Document, lead: str, body: str) -> None:
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.space_after = Pt(3)
    run = p.add_run(lead)
    run.bold = True
    run.font.name = "Arial"
    p.add_run(body)


def add_heading(doc: Document, text: str, level=1) -> None:
    p = doc.add_heading(text, level=level)
    p.paragraph_format.keep_with_next = True


def add_page_number(paragraph) -> None:
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = paragraph.add_run("ShockSat advisor memo  |  ")
    run.font.name = "Arial"
    run.font.size = Pt(8)
    run.font.color.rgb = rgb(GREY)
    fld_char1 = OxmlElement("w:fldChar")
    fld_char1.set(qn("w:fldCharType"), "begin")
    instr_text = OxmlElement("w:instrText")
    instr_text.set(qn("xml:space"), "preserve")
    instr_text.text = "PAGE"
    fld_char2 = OxmlElement("w:fldChar")
    fld_char2.set(qn("w:fldCharType"), "end")
    run._r.append(fld_char1)
    run._r.append(instr_text)
    run._r.append(fld_char2)


def configure_document(doc: Document) -> None:
    section = doc.sections[0]
    section.page_width = Inches(8.5)
    section.page_height = Inches(11)
    section.top_margin = Inches(0.72)
    section.bottom_margin = Inches(0.65)
    section.left_margin = Inches(0.82)
    section.right_margin = Inches(0.82)
    section.header_distance = Inches(0.3)
    section.footer_distance = Inches(0.32)

    normal = doc.styles["Normal"]
    normal.font.name = "Arial"
    normal.font.size = Pt(10.2)
    normal.font.color.rgb = rgb(INK)
    normal.paragraph_format.line_spacing = 1.08
    normal.paragraph_format.space_after = Pt(5)

    for level, size, before, after in ((1, 16, 13, 6), (2, 12.5, 10, 4), (3, 11, 7, 3)):
        style = doc.styles[f"Heading {level}"]
        style.font.name = "Arial"
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = rgb(BLUE if level < 3 else NAVY)
        style.paragraph_format.space_before = Pt(before)
        style.paragraph_format.space_after = Pt(after)
        style.paragraph_format.keep_with_next = True

    caption = doc.styles["Caption"]
    caption.font.name = "Arial"
    caption.font.size = Pt(8.5)
    caption.font.italic = False
    caption.font.bold = False
    caption.font.color.rgb = rgb(GREY)
    caption.paragraph_format.line_spacing = 1.0

    for section in doc.sections:
        add_page_number(section.footer.paragraphs[0])


