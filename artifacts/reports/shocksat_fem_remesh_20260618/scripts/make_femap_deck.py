#!/usr/bin/env python3
"""Generate a self-contained NASTRAN SOL103 normal-modes deck at a given
theta (part-group stiffness scales) for the FEMAP cross-check.

theta scaling is applied WITHOUT touching geometry:
  - shell groups: each (group, material) pair gets a COPY of its MAT1 with
    E and G scaled by theta_g (stiffness is linear in E,G; rho unchanged so
    mass is identical), and the group's PSHELLs point to the copy;
  - bush groups: PBUSH K values scaled by theta_g directly.
The deck is emitted from `fem_model.npz` (the validated parse), so it
contains exactly the model we assembled (Shock_Test_Instrumentation dropped,
decision D10).

Usage:
  python make_femap_deck.py nominal
  python make_femap_deck.py posterior --theta-json femap_handoff/theta_posterior_mean.json
Output: femap_handoff/shocksat_modal_twin_<tag>.dat
"""
import argparse
import json
import os
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("tag")
ap.add_argument("--theta-json", default=None,
                help="JSON {group: theta}; omitted = all 1.0 (nominal)")
args = ap.parse_args()

z = np.load("fem_model.npz", allow_pickle=True)
groups = json.load(open("groups.json"))["groups"]
pshell = json.loads(str(z["pshell"]))
pbush = json.loads(str(z["pbush"]))
mat1 = json.loads(str(z["mat1"]))
cords = json.loads(str(z["cords"]))

theta = {g: 1.0 for g in groups}
if args.theta_json:
    theta.update(json.load(open(args.theta_json)))

pid2group = {}
for g, members in groups.items():
    for m in members:
        kind, pid = m.split("_")
        pid2group[(kind, int(pid))] = g

def f8(x):
    """8-char NASTRAN small-field float."""
    if x == 0:
        return "0.0"
    for fmt in ("%8.6G", "%8.5G", "%8.4G", "%8.3G"):
        s = (fmt % x).strip().replace("E+0", "+").replace("E-0", "-") \
                             .replace("E+", "+").replace("E-", "-")
        if "." not in s and "+" not in s and "-" not in s[1:]:
            s += "."
        if len(s) <= 8:
            return s
    raise ValueError(f"cannot format {x}")

def card(*fields):
    """small-field card, auto-continuation every 8 data fields."""
    out, name = [], fields[0]
    rest = list(fields[1:])
    line = f"{name:<8}"
    n = 0
    for f in rest:
        if n == 8:
            out.append(line)
            line = f"+{'':<7}"
            n = 0
        line += f"{str(f):<8}"
        n += 1
    out.append(line)
    return "\n".join(o.rstrip() for o in out)

L = []
L.append("$ ShockSat modal twin FEMAP cross-check deck")
L.append(f"$ tag = {args.tag}; theta = {json.dumps(theta)}")
L.append("$ generated by make_femap_deck.py from the validated parse")
L.append("SOL 103")
L.append("CEND")
L.append("TITLE = ShockSat modal twin cross-check (%s)" % args.tag)
L.append("METHOD = 1")
L.append("DISPLACEMENT(PLOT) = ALL")
L.append("BEGIN BULK")
L.append(card("PARAM", "K6ROT", "100."))
L.append(card("PARAM", "COUPMASS", "-1"))
L.append(card("EIGRL", 1, "-1.", "350."))   # NORM defaults to MASS

# coordinate frames
for cid, c in cords.items():
    R = np.array(c["R"]); o = np.array(c["origin"])
    b = o + R[2]                # point on z axis
    cpt = o + R[0]              # point in x-z plane
    L.append(card(c["type"], cid, "", *(f8(v) for v in o),
                  *(f8(v) for v in b), *(f8(v) for v in cpt)))

# materials: original + per-(group,mid) scaled copies
newmid = {}
for mid, m in mat1.items():
    L.append(card("MAT1", mid, f8(m["E"]), f8(m["G"]), f8(m["nu"]),
                  f8(m["rho"])))
copy_counter = 100
for (kind, pid), g in sorted(pid2group.items()):
    if kind != "shell":
        continue
    th = theta[g]
    for slot in ("mid1", "mid2", "mid3"):
        mid = pshell[str(pid)][slot]
        if mid == 0:
            continue
        key = (g, mid)
        if key not in newmid:
            if abs(th - 1.0) < 1e-12:
                newmid[key] = mid          # nominal: reuse original
            else:
                copy_counter += 1
                newmid[key] = copy_counter
                m = mat1[str(mid)]
                L.append(card("MAT1", copy_counter, f8(m["E"] * th),
                              f8(m["G"] * th), f8(m["nu"]), f8(m["rho"])))

# PSHELL pointing at (possibly) scaled materials
for pid, p in sorted(pshell.items(), key=lambda kv: int(kv[0])):
    g = pid2group[("shell", int(pid))]
    m1 = newmid.get((g, p["mid1"]), p["mid1"])
    m2 = newmid.get((g, p["mid2"]), p["mid2"]) if p["mid2"] else ""
    m3 = newmid.get((g, p["mid3"]), p["mid3"]) if p["mid3"] else ""
    L.append(card("PSHELL", pid, m1, f8(p["t"]), m2, f8(p["bend_ratio"]),
                  m3, f8(p["ts_t"]), f8(p["nsm"])))

# PBUSH with scaled K
for pid, p in sorted(pbush.items(), key=lambda kv: int(kv[0])):
    g = pid2group.get(("bush", int(pid)))
    th = theta[g] if g else 1.0            # PBUSH 99 fixed -> th=1
    L.append(card("PBUSH", pid, "K", *(f8(k * th) for k in p["k"])))

# grids
for gid, xyz in zip(z["gids"], z["xyz"]):
    L.append(card("GRID", int(gid), "", *(f8(v) for v in xyz)))

# elements
for q in z["cquad4"]:
    L.append(card("CQUAD4", *(int(v) for v in q)))
for t in z["ctria3"]:
    L.append(card("CTRIA3", *(int(v) for v in t)))
for b in z["cbush"]:
    eid, pid, ga, gb, cid = (int(v) for v in b)
    L.append(card("CBUSH", eid, pid, ga, gb, "", "", "",
                  cid if cid else ""))
for c in z["conm2"]:
    eid, gid = int(c[0]), int(c[1])
    m, x1, x2, x3 = c[2], c[3], c[4], c[5]
    I11, I21, I22, I31, I32, I33 = c[6:12]
    L.append(card("CONM2", eid, gid, 0, f8(m), f8(x1), f8(x2), f8(x3), "",
                  f8(I11), f8(I21), f8(I22), f8(I31), f8(I32), f8(I33)))

# RBE2
gms = z["rbe2_gms"]; ptr = 0
for eid, gn, cm, n in z["rbe2"]:
    dep = [int(x) for x in gms[ptr:ptr + n]]; ptr += n
    L.append(card("RBE2", int(eid), int(gn), int(cm), *dep))

L.append("ENDDATA")
os.makedirs("femap_handoff", exist_ok=True)
path = f"femap_handoff/shocksat_modal_twin_{args.tag}.dat"
open(path, "w").write("\n".join(L) + "\n")
print(f"wrote {path}: {len(L)} lines, theta = {theta}")
